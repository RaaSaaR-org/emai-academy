# config/ holds no absolute paths. Everything that depends on the checkout location is
# generated here into .run/ on every script run, so a fresh clone anywhere works.
write_generated_config() {
  cat >"$GEN_BACKEND_TOML" <<TOML
# GENERATED by scripts/lib.sh - do not edit. First entry of ACADEMY_CONFIG.
[finance]
invoices_archive = "$STATE_DIR/invoices"
credit_notes_archive = "$STATE_DIR/credit_notes"
final_statements_archive = "$STATE_DIR/final_statements"
TOML
  {
    echo "# GENERATED by scripts/lib.sh from config/skills-ms.env plus checkout paths - do not edit."
    cat "$CONFIG_DIR/skills-ms.env"
    echo
    echo "# --- content paths (absolute, computed from EMAI_ROOT=$EMAI_ROOT) ---"
    echo "COURSES=$CONTENT_DIR/courses"
    echo "LEARNING_ROOMS_CONTENT=$CONTENT_DIR/learning_rooms.json"
    echo "CHARACTER_AREAS=$CONTENT_DIR/character_areas.json"
    echo "MP4_LECTURES=$CONTENT_DIR/lectures"
    [ -d "$CONTENT_DIR/courses-private" ] && echo "PRIVATE_COURSES_DIRECTORY=$CONTENT_DIR/courses-private"
    [ -d "$CONTENT_DIR/lesson-modules-private" ] && echo "PRIVATE_LESSON_MODULES_ROOT=$CONTENT_DIR/lesson-modules-private"
    true
  } >"$GEN_SKILLS_ENV"
}
write_generated_config

log() { printf '\033[38;5;208m[emai]\033[0m %s\n' "$*"; }
die() { printf '\033[31m[emai] %s\033[0m\n' "$*" >&2; exit 1; }

port_pid() { lsof -tiTCP:"$1" -sTCP:LISTEN -n -P 2>/dev/null | head -1; }
port_busy() { [ -n "$(port_pid "$1")" ]; }

wait_http() { # url timeout_seconds
  local url=$1 t=${2:-60} i=0
  while [ "$i" -lt "$t" ]; do
    curl -fsS -o /dev/null --max-time 2 "$url" 2>/dev/null && return 0
    sleep 1; i=$((i + 1))
  done
  return 1
}

# Run a command inside the backend dev shell (direnv/devenv) with the EmAI config.
backend_exec() {
  direnv exec "$BACKEND_DIR" sh -c "cd '$BACKEND_DIR' && ACADEMY_CONFIG='$ACADEMY_CONFIG_EMAI' exec \"\$@\"" sh "$@"
}

# The EmAI backend runs a PINNED copy of the backend binary in .state/bin/. Without the copy it
# would run ../backend/target/debug/academy, which every Bootstrap rebuild replaces, so the EmAI
# backend (and its embedded DB migrations) would change on its next restart without notice.
# Refresh on purpose with: scripts/dev-up.sh --refresh-backend (or EMAI_REFRESH_BACKEND=1).
backend_bin() {
  local pinned="$STATE_DIR/bin/academy" built="$BACKEND_DIR/target/debug/academy"
  if [ -x "$pinned" ] && [ -z "${EMAI_REFRESH_BACKEND:-}" ]; then
    echo "$pinned"
    return
  fi
  if [ ! -x "$built" ] || [ -n "${EMAI_REFRESH_BACKEND:-}" ]; then
    log "building the backend (cargo build in $BACKEND_DIR)"
    direnv exec "$BACKEND_DIR" sh -c "cd '$BACKEND_DIR' && cargo build" >&2 || die "cargo build failed"
  fi
  mkdir -p "$STATE_DIR/bin"
  cp "$built" "$pinned.tmp" && mv "$pinned.tmp" "$pinned"
  git -C "$BACKEND_DIR" rev-parse HEAD >"$STATE_DIR/bin/academy.rev" 2>/dev/null || true
  log "pinned backend binary at $(cat "$STATE_DIR/bin/academy.rev" 2>/dev/null || echo '?') -> $pinned" >&2
  echo "$pinned"
}

# Export the skills-ms environment, then point any content path that doesn't exist yet
# at the boot placeholders (config/placeholders). Real content under content/ always wins.
skills_env() {
  set -a
  # shellcheck disable=SC1091
  . "$GEN_SKILLS_ENV"
  set +a
  [ -f "$LEARNING_ROOMS_CONTENT" ] || { log "WARN: $LEARNING_ROOMS_CONTENT missing, using placeholder"; export LEARNING_ROOMS_CONTENT="$PLACEHOLDER_DIR/learning_rooms.json"; }
  [ -f "$CHARACTER_AREAS" ] || { log "WARN: $CHARACTER_AREAS missing, using placeholder"; export CHARACTER_AREAS="$PLACEHOLDER_DIR/character_areas.json"; }
  if ! ls "$COURSES"/*.yml >/dev/null 2>&1; then
    log "WARN: no course files in $COURSES, using placeholder"; export COURSES="$PLACEHOLDER_DIR/courses"
  fi
  # Optional overlays: they must be real directories, so leave them unset when absent.
  [ -d "${PRIVATE_COURSES_DIRECTORY:-/nonexistent}" ] || unset PRIVATE_COURSES_DIRECTORY
  [ -d "${PRIVATE_LESSON_MODULES_ROOT:-/nonexistent}" ] || unset PRIVATE_LESSON_MODULES_ROOT
  export PYTHONDONTWRITEBYTECODE=1
}

# skills-ms-rooms venv. Built with `nix develop` (poe setup = poetry install --sync).
# greenlet is not installed by the lock on macOS arm64 (platform_machine == "arm64" isn't in
# its markers), but SQLAlchemy asyncio needs it, so it is pip-installed on top.
# `nix develop` runs `poetry install --sync` again and removes it, so we call .venv directly.
skills_venv() {
  if [ ! -x "$SKILLS_DIR/.venv/bin/python" ]; then
    log "creating skills-ms-rooms/.venv via nix develop (first run takes a while)"
    (cd "$SKILLS_DIR" && nix develop --command true) >&2 || die "nix develop failed in skills-ms-rooms"
  fi
  if ! "$SKILLS_DIR/.venv/bin/python" -c 'import greenlet' 2>/dev/null; then
    log "installing greenlet into skills-ms-rooms/.venv"
    "$SKILLS_DIR/.venv/bin/python" -m pip install -q 'greenlet==3.0.3' >&2 || die "greenlet install failed"
  fi
  # poe tasks read .env; keep it pointing at the tenant env (untracked, gitignored upstream).
  if [ ! -L "$SKILLS_DIR/.env" ] && [ -e "$SKILLS_DIR/.env" ]; then
    mv "$SKILLS_DIR/.env" "$SKILLS_DIR/.env.bak.$(date +%s)"
  fi
  ln -sfn "$GEN_SKILLS_ENV" "$SKILLS_DIR/.env"
}

ensure_db() { # name
  if ! "$PG_BIN/psql" -h 127.0.0.1 -U academy -d academy -Atc "select 1 from pg_database where datname='$1'" | grep -q 1; then
    log "creating database $1"
    "$PG_BIN/createdb" -h 127.0.0.1 -U academy "$1"
  fi
}
